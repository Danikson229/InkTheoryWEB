/* ===== Contact form: sends an email to lyverostudio@gmail.com via FormSubmit ===== */
const form = $("form"), statusEl = $("status"), sendBtn = $("send");
const MAIL_TO = atob("bHl2ZXJvc3R1ZGlvQGdtYWlsLmNvbQ=="); // replace with the FormSubmit hashed ID to hide the address completely
form.addEventListener("submit", async (e) => {
  e.preventDefault();
  const d = Object.fromEntries(new FormData(form));
  if (d._honey) return; // spam bot
  let bad = false;
  form.querySelectorAll("input[required],textarea[required]").forEach((f) => {
    const ok = f.value.trim() && f.checkValidity();
    f.setAttribute("aria-invalid", ok ? "false" : "true");
    if (!ok) bad = true;
  });
  statusEl.className = "status";
  if (bad) { statusEl.textContent = t("f_bad"); statusEl.classList.add("err"); return; }
  sendBtn.disabled = true;
  sendBtn.textContent = t("f_sending");
  statusEl.textContent = "";
  try {
    const r = await fetch("https://formsubmit.co/ajax/" + MAIL_TO, {
      method: "POST",
      headers: { "Content-Type": "application/json", Accept: "application/json" },
      body: JSON.stringify({
        Name: d.name, Email: d.email, "Telegram / phone": d.contact || "-",
        "Project type": d.type || "-", Budget: d.budget || "-", Project: d.message,
        _subject: "New project request from Lyvero Studio: " + d.name,
        _replyto: d.email, _template: "table", _captcha: "false", _autoresponse: t("f_auto"),
      }),
    });
    const j = await r.json();
    if (!r.ok || String(j.success) !== "true") throw new Error("send failed");
    form.reset();
    statusEl.textContent = t("f_ok");
    statusEl.classList.add("ok");
  } catch (err) {
    statusEl.textContent = t("f_err");
    statusEl.classList.add("err");
  } finally {
    sendBtn.disabled = false;
    sendBtn.textContent = t("f_send");
  }
});
